package paper_f7b72c81_3a1a_489b_8264_a1225dde6630;

import core.*;

/**
 * 《資訊不可能三角》
 * The Information Trilemma
 * UUID: f7b72c81-3a1a-489b-8264-a1225dde6630
 */
public class Concepts {

    // ===================================================================
    // 葉節點（僅依賴 core 原語）
    // ===================================================================

    /**
     * 規則集在特定條件下相互作用的整體效應 C(R)。
     * 可直接觀察、可測量。規則集跨條件不變，
     * 但各規則的相對權重與交互方式隨條件改變。
     */
    public record 組合表現(
        規則 基礎規則
    ) {}

    /**
     * 系統內部的推理一致性。
     * ∀ p, q ∈ System: ¬(p ∧ ¬p)
     * 無命名子結構，空 record。
     */
    public record 邏輯() {}

    // ===================================================================
    // 依賴 組合表現 的概念
    // ===================================================================

    /**
     * 使組合表現相同的條件的等價類，以 s 表示。
     * 記為 C(R, s) 時，s 是對「產生相同組合表現的條件集合」的命名。
     * 尺度 由組合表現的可觀察差異歸納得出，不是先驗分類。
     */
    public record 尺度(
        規則 基礎規則,
        組合表現 對應組合表現
    ) {}

    // ===================================================================
    // 依賴 尺度 的概念
    // ===================================================================

    /**
     * 與特定尺度下可驗證的現實吻合。
     * Truth(s)：System 輸出 ↦ C(R, s)
     */
    public record 真實(
        尺度 所在尺度
    ) {}

    /**
     * 特定尺度下對 C(R, s) 的有損文本化記錄。
     * K(s) ≠ C(R, s)（觀察事實四：知識有損性）。
     */
    public record 知識(
        尺度 所在尺度
    ) {}

    // ===================================================================
    // 依賴 知識 的概念
    // ===================================================================

    /**
     * 同時容納多個不同尺度下各自充分的知識體系。
     * 規模不是資料量，是知識多樣性（跨越多少個不同的尺度）。
     */
    public record 規模(
        知識 知識體系樣本
    ) {}

    // ===================================================================
    // 頂層概念
    // ===================================================================

    /**
     * 以 {規模, 邏輯, 真實} 為頂點的結構性取捨約束。
     * 當規模開放時，統一的邏輯與所有尺度下的真實不可同時滿足。
     */
    public record 資訊不可能三角(
        規模 規模頂點,
        邏輯 邏輯頂點,
        真實 真實頂點
    ) {}

    // ===================================================================
    // 公設（觀察事實）
    // ===================================================================

    public static final Postulate 觀察事實一 = new Postulate(
        "觀察事實一",
        "F1: 規則集跨尺度不變——四大基本力在所有尺度下都存在，R(s) = R"
    );

    public static final Postulate 觀察事實二 = new Postulate(
        "觀察事實二",
        "F2: 具體現象 = 組合表現，即 具體現象(s) ≡ C(R, s)"
    );

    public static final Postulate 觀察事實三 = new Postulate(
        "觀察事實三",
        "F3: 存在可區分的組合表現 regime——∃ s₁ ≠ s₂: C(R, s₁) ≠ C(R, s₂)；不依賴湧現"
    );

    public static final Postulate 知識有損性 = new Postulate(
        "知識有損性",
        "F4: K(s) 不完整反映 C(R, s)——加重條件，非三角成立必要條件"
    );
}
