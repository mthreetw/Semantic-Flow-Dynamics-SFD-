    public static final Postulate 黑箱律 = new Postulate(
        "黑箱律",
        "語意流的下一刻方向不可由當下方向與信號決定。" +
        "不存在函數 f 使得 SemanticFlow(t+1) = f(SemanticFlow(t), Signal(t))。" +
        "差別在於思考——思考是讓 f 不存在的原因。思考不是計算。"
    );

